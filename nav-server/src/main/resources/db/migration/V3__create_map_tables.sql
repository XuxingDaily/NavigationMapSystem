CREATE TABLE public.map_layer (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(64) NOT NULL UNIQUE,
    name            VARCHAR(100) NOT NULL,
    geometry_type   VARCHAR(30),
    source_file     VARCHAR(255),
    min_zoom        INTEGER NOT NULL DEFAULT 0,
    max_zoom        INTEGER NOT NULL DEFAULT 22,
    enabled         BOOLEAN NOT NULL DEFAULT true,
    data_version    BIGINT NOT NULL DEFAULT 1,
    style_config    JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT map_layer_zoom_range_ck CHECK (
        min_zoom >= 0
        AND max_zoom <= 22
        AND min_zoom <= max_zoom
    )
);

CREATE TABLE public.map_feature (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    layer_id            BIGINT NOT NULL REFERENCES public.map_layer(id),
    source_feature_id   VARCHAR(100),
    name                VARCHAR(255),
    properties          JSONB NOT NULL DEFAULT '{}'::jsonb,
    geom_local          geometry(Geometry, 0) NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_map_feature_not_empty
        CHECK (NOT ST_IsEmpty(geom_local)),
    CONSTRAINT ck_map_feature_local_srid
        CHECK (ST_SRID(geom_local) = 0)
);

CREATE INDEX idx_map_feature_layer
    ON public.map_feature (layer_id);
CREATE INDEX idx_map_feature_geom_local
    ON public.map_feature USING GIST (geom_local);
CREATE INDEX idx_map_feature_properties
    ON public.map_feature USING GIN (properties);
