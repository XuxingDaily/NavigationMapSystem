CREATE TABLE public.road_node (
    id              BIGINT PRIMARY KEY,
    geom_local      geometry(Point, 0) NOT NULL,
    network_version BIGINT NOT NULL DEFAULT 1,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT road_node_geom_local_valid_ck CHECK (
        ST_SRID(geom_local) = 0
        AND GeometryType(geom_local) = 'POINT'
        AND NOT ST_IsEmpty(geom_local)
    )
);

CREATE TABLE public.road_edge (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source              BIGINT NOT NULL REFERENCES public.road_node(id),
    target              BIGINT NOT NULL REFERENCES public.road_node(id),
    name                VARCHAR(200) NOT NULL,
    instruction         VARCHAR(50),
    road_type           VARCHAR(50),
    geom_local          geometry(LineString, 0) NOT NULL,
    length_m            DOUBLE PRECISION NOT NULL,
    speed_kmh           DOUBLE PRECISION,
    driving_cost_s      DOUBLE PRECISION,
    driving_reverse_s   DOUBLE PRECISION,
    walking_cost_s      DOUBLE PRECISION,
    walking_reverse_s   DOUBLE PRECISION,
    one_way             BOOLEAN,
    bridge              BOOLEAN,
    tunnel              BOOLEAN,
    access_car          BOOLEAN,
    access_walk         BOOLEAN,
    coordinate_status   VARCHAR(20) NOT NULL DEFAULT 'local_only',
    status              VARCHAR(20) NOT NULL DEFAULT 'active',
    network_version     BIGINT NOT NULL DEFAULT 1,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    description         TEXT,

    CONSTRAINT road_edge_different_nodes_ck CHECK (source <> target),
    CONSTRAINT road_edge_positive_length_ck CHECK (length_m > 0),
    CONSTRAINT road_edge_geom_local_valid_ck CHECK (
        ST_SRID(geom_local) = 0
        AND GeometryType(geom_local) = 'LINESTRING'
        AND ST_NPoints(geom_local) >= 2
        AND NOT ST_IsEmpty(geom_local)
    )
);

CREATE TABLE public.poi (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                TEXT NOT NULL,
    context             TEXT,
    geom_local          geometry(Point, 0) NOT NULL,
    coordinate_status   VARCHAR(20) NOT NULL DEFAULT 'local_only',
    status              VARCHAR(20) NOT NULL DEFAULT 'active',
    data_version        BIGINT NOT NULL DEFAULT 1,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT poi_geom_local_valid_ck CHECK (
        ST_SRID(geom_local) = 0
        AND GeometryType(geom_local) = 'POINT'
        AND NOT ST_IsEmpty(geom_local)
    )
);

CREATE INDEX road_node_geom_local_gix
    ON public.road_node USING GIST (geom_local);

CREATE INDEX road_edge_geom_local_gix
    ON public.road_edge USING GIST (geom_local);
CREATE INDEX road_edge_source_idx
    ON public.road_edge (source);
CREATE INDEX road_edge_target_idx
    ON public.road_edge (target);
CREATE INDEX road_edge_source_target_idx
    ON public.road_edge (source, target);

CREATE INDEX poi_geom_local_gix
    ON public.poi USING GIST (geom_local);
CREATE INDEX poi_name_idx
    ON public.poi (name);
